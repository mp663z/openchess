import re,sys,os
task,name,title,mod,ref,tests_file,mut_file=sys.argv[1:8]
txt=open(tests_file).read()
names=re.findall(r"^def (test_\w+)",txt,re.M)
mapping="\n".join(f"- `{n}`" for n in names)
out=f"""# {task} {title}

## Normative requirements

1. `{os.path.basename(tests_file)}` proves happy, boundary, malformed and rollback behavior of the production `server.{mod}` across process restarts. It adds no production code.
2. The durable value of the engine is persisted as canonical JSON under tmp_path (atomic replace), the production module is imported anew, and the stream continues. Sampled streams (12 restarted at every step, 10 with one random cut point, 3 with four steps each run in a real child interpreter) must give the same outcomes and the same durable value as an uninterrupted run and as the contract's reference implementation (`tests.{ref}`), which is the differential oracle.
3. Replaying the same seeded stream after restarts (6 seeds) gives identical outcomes, and receipt identifiers are one per distinct receipt. Only the restart battery (T0353) mixes the real queue engine into its streams.
4. Forged or malformed inputs are refused with the oracle's failure class and code, leave their input structurally identical, and the next valid request still succeeds. They are built from the persisted value when it is a previous record or a queue state (fields dropped or retyped, digest not recomputed), and from the request fields otherwise (retry and dead-letter carry no previous record). Digest-recomputed forgeries are not generated by this battery. A truncated durable file is a host-level JSON error and never reaches the engine; the last good file stays usable.
5. Boundary rows pin the exact bounds a restarted engine can reach, with the oracle as the expected value.

## Requirement-to-test mapping

{mapping}

## Mutation check

{open(mut_file).read().strip()}
"""
os.makedirs(os.environ['WT']+'/requirements/tasks',exist_ok=True)
open(os.environ['WT']+f'/requirements/tasks/{task}.md','w').write(out)
