# -- expectation evaluation -------------------------------------------------------

_MISSING = object()


def _at(document, path):
    node = document
    for key in path:
        if (
            type(node) is dict
            and key in node
            or type(node) is list
            and type(key) is int
            and -len(node) <= key < len(node)
        ):
            node = node[key]
        else:
            return _MISSING
    return node


def _failures_of_check(document, check):
    value = _at(document, check["at"])
    where = "/".join(str(k) for k in check["at"])
    if "equals" in check:
        if value != check["equals"] or type(value) is not type(check["equals"]):
            return [f"{where}: expected {check['equals']!r}"]
    elif "absent" in check:
        if value is not _MISSING:
            return [f"{where}: expected absent"]
    elif (
        type(value) not in (dict, list)
        or ([*value] if type(value) is dict else value) != check["keys"]
    ):
        return [f"{where}: expected keys {check['keys']!r}"]
    return []


def _containers(value, out):
    stack = [value]
    while stack:
        node = stack.pop()
        if type(node) is dict:
            out.add(id(node))
            stack.extend(node.values())
        elif type(node) is list:
            out.add(id(node))
            stack.extend(node)
    return out


def _outcome(source):
    """('document', doc) or ('refusal', error) with the shared invariants."""
    before = copy.deepcopy(source)
    problems = []
    try:
        document = _derive(source)
    except _REF.OpenApiError as error:
        if (error.failure_class, error.code, error.retryable) != (FAILURE, CODE, False):
            problems.append(f"refusal shape {error.failure_class}/{error.code}")
        if error.__cause__ is not None or error.__context__ is not None:
            problems.append("refusal carries a cause or context")
        outcome = ("refusal", None)
    else:
        outcome = ("document", document)
        bytes_one = _REF.canonical_bytes(document)
        json.loads(bytes_one)
        if _REF.canonical_bytes(_derive(copy.deepcopy(before))) != bytes_one:
            problems.append("derivation is not deterministic")
        if _containers(document, set()) & _containers(source, set()):
            problems.append("document shares a container with the source")
    if source != before:
        problems.append("source was changed")
    return outcome, problems


def _run_row(row):
    """The list of semantic failures for one row; empty means the row holds."""
    source = _materialize(row["mutations"], row["name"])
    (kind, document), problems = _outcome(source)
    failures = list(problems)
    expect = row["expect"]
    if expect["kind"] == "refusal":
        if kind != "refusal":
            failures.append("derivation accepted a malformed source")
    elif kind != "document":
        failures.append("derivation refused a valid source")
    else:
        for check in expect["checks"]:
            failures.extend(_failures_of_check(document, check))
    if row.get("then_baseline"):
        (base_kind, base), base_problems = _outcome(_shipped())
        failures.extend(base_problems)
        if base_kind != "document" or _digest(base) != GOLDEN:
            failures.append("baseline after the row is not the golden document")
    return failures


def _digest(document):
    return hashlib.sha256(_REF.canonical_bytes(document)).hexdigest()


GOLDEN = _REF.GOLDEN_SHA256
ROWS = [(s, r) for s in SECTIONS for r in CASES[s]]


def test_golden_digest_is_the_pinned_t0419_baseline():
    (kind, document), problems = _outcome(_shipped())
    assert (kind, problems) == ("document", [])
    assert _digest(document) == GOLDEN
    assert len(_REF.canonical_bytes(document)) == _REF.GOLDEN_LENGTH


@pytest.mark.parametrize("section,row", ROWS, ids=[f"{s}:{r['name']}" for s, r in ROWS])
def test_row_holds_against_the_reference(section, row):
    assert _run_row(row) == []


# -- mutant battery: behavioral one-edit defects of derive ------------------------


def _post(transform):
    def mutate(derive):
        def mutant(source):
            document = derive(source)
            transform(document)
            return document

        return mutant

    return mutate


def _drop_idempotency(document):
    for item in document["paths"].values():
        for operation in item.values():
            operation["parameters"] = []


def _public_gets_bearer(document):
    document["paths"]["/identity/register"]["post"]["security"] = [{"bearerAuth": []}]


def _bearer_dropped(document):
    document["paths"]["/identity/refresh"]["post"]["security"] = []


def _sort_properties(document):
    schema = document["paths"]["/identity/register"]["post"]["requestBody"]["content"][
        "application/json"
    ]["schema"]
    schema["properties"] = dict(sorted(schema["properties"].items()))


def _optional_is_required(document):
    schema = document["paths"]["/identity/register"]["post"]["requestBody"]["content"][
        "application/json"
    ]["schema"]
    schema["required"] = list(schema["properties"])


def _invent_status(document):
    for item in document["paths"].values():
        for operation in item.values():
            if operation["operationId"] == "identity.login":
                operation["responses"]["429"] = {"description": "error"}


def _sort_paths(document):
    document["paths"] = dict(sorted(document["paths"].items()))


def _wrong_info_version(document):
    document["info"]["version"] = document["info"]["version"] + ".0.0"


def _wrong_server(document):
    document["servers"] = [{"url": "/"}]


def _lose_unmapped(document):
    document["x-unmapped-error-codes"] = []


def _status_group(document):
    responses = document["paths"]["/identity/refresh"]["post"]["responses"]
    if "401" in responses:
        responses["401"]["x-error-codes"] = ["auth_invalid", "auth_expired"]


def _public_is_listed_only(derive):
    """Accepts a source whose public list omits a public operation."""

    def mutant(source):
        try:
            return derive(source)
        except _REF.OpenApiError:
            if type(source) is not dict:
                raise
            patched = copy.deepcopy(source)
            patched["contract"]["transport"]["auth"]["public_operations"] = [
                "identity.register",
                "identity.login",
            ]
            return derive(patched)

    return mutant


def _lax_base_path(derive):
    def mutant(source):
        try:
            return derive(source)
        except _REF.OpenApiError:
            if type(source) is not dict:
                raise
            patched = copy.deepcopy(source)
            patched["contract"]["versioning"]["base_path"] = "/cp/v1"
            return derive(patched)

    return mutant


def _swallow_refusals(derive):
    def mutant(source):
        try:
            return derive(source)
        except _REF.OpenApiError:
            return {"openapi": "3.1.0"}

    return mutant


def _mutates_source(derive):
    def mutant(source):
        document = derive(source)
        source["areas"]["identity"]["ops"]["register"]["errors"].sort()
        return document

    return mutant


def _shares_containers(derive):
    def mutant(source):
        document = derive(source)
        document["x-unmapped-error-codes"] = source["contract"]["transport"]["read_only_operations"]
        return document

    return mutant


def _nondeterministic(derive):
    calls = []

    def mutant(source):
        document = derive(source)
        calls.append(1)
        if len(calls) % 2 == 0:
            document["info"]["title"] += "!"
        return document

    return mutant


def _typed_refusal_carries_context(derive):
    def mutant(source):
        try:
            return derive(source)
        except _REF.OpenApiError as error:
            raise _REF.OpenApiError(error.failure_class, error.code, str(error)) from error

    return mutant


def _retryable_refusal(derive):
    def mutant(source):
        try:
            return derive(source)
        except _REF.OpenApiError:
            error = _REF.OpenApiError(FAILURE, CODE, "malformed")
            error.retryable = True
            raise error from None

    return mutant


def _wrong_refusal_code(derive):
    def mutant(source):
        try:
            return derive(source)
        except _REF.OpenApiError:
            raise _REF.OpenApiError(FAILURE, "internal", "malformed") from None

    return mutant


def _stateful_after_refusal(derive):
    state = {"refused": False}

    def mutant(source):
        try:
            document = derive(source)
        except _REF.OpenApiError:
            state["refused"] = True
            raise
        if state["refused"]:
            document["info"]["version"] = "0"
        return document

    return mutant


