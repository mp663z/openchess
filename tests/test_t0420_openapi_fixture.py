"""T0420: closed, executable fixture for the OpenAPI derivation contract.

The corpus (tests/fixtures/openapi/cases.json, generated by
tools/openapi_fixture_generate.py) is a set of exact mutation lists over the
shipped control-plane source plus expectations authored from the structured
contract (data/contracts/openapi.yaml), never computed by the reference.
Every row executes against the T0419 test-only reference derive() as a
separate binding. Sections:

- happy: the baseline document shape, security, idempotency, schema and
  error-response rules, and additive field changes;
- boundary: major, name, route and example-magnitude ceilings, each as an
  accepted edge and a refused step past it;
- malformed: source shape, grammar, cross-reference, example, write-only and
  chess-token violations refuse typed;
- rollback: refusals leave the source bit-identical, return no document and
  disturb nothing: the shipped source still derives the pinned golden bytes.

Every row also runs the shared invariants (source unchanged, typed fresh
refusal, deterministic canonical bytes, detached document). The mutant
battery wraps derive with one-edit behavioral defects; every kill is a
failed fixture row, never a crash or a source-text check.
"""

from __future__ import annotations

import copy
import hashlib
import json
import sys
from pathlib import Path

import pytest
import yaml

import tests.test_t0419_openapi_contract as _REF
import tools.openapi_fixture_generate as _GEN

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "tests" / "fixtures" / "openapi" / "cases.json"
CASES = json.loads(FIXTURE.read_text())
SOURCE_PATH = ROOT / CASES["source"]
SECTIONS = ("happy", "boundary", "malformed", "rollback")
TOP_KEYS = {
    "schema_version",
    "contract",
    "contract_schema_version",
    "source",
    "notes",
    "source_manifest",
    "section_manifests",
    *SECTIONS,
}
ROW_KEYS = {"name", "why", "mutations", "expect"}
ACTIONS = {
    "set": {"path", "value"},
    "del": {"path"},
    "append": {"path", "value"},
    "replace_root": {"value"},
}
FAILURE = "malformed_control_plane"
CODE = "malformed_request"


def _derive(source):
    """Late-bound so the mutant battery can rebind the reference."""
    return _REF.derive(source)


def _canon(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":")).encode()


_SHIPPED_TEXT = SOURCE_PATH.read_text()
_SHIPPED_DOC = yaml.safe_load(_SHIPPED_TEXT)


def _shipped():
    return copy.deepcopy(_SHIPPED_DOC)


# -- mutation materialization ---------------------------------------------------


class FixtureError(Exception):
    """A corpus row that cannot be materialized against the shipped source."""


def _resolve(doc, path, where):
    node = doc
    for key in path[:-1]:
        if type(node) is not dict or key not in node:
            raise FixtureError(f"{where}: unresolvable path {path}")
        node = node[key]
    if type(node) is not dict:
        raise FixtureError(f"{where}: unresolvable path {path}")
    return node, path[-1]


def _materialize(mutations, where):
    doc = _shipped()
    for mutation in mutations:
        assert type(mutation) is dict and len(mutation) == 1, where
        (action,) = mutation
        spec = mutation[action]
        assert action in ACTIONS and set(spec) == ACTIONS[action], where
        if action == "replace_root":
            doc = copy.deepcopy(spec["value"])
            continue
        path = spec["path"]
        assert type(path) is list and path and all(type(k) is str for k in path), where
        node, last = _resolve(doc, path, where)
        if action == "set":
            node[last] = copy.deepcopy(spec["value"])
        elif action == "del":
            if last not in node:
                raise FixtureError(f"{where}: del of missing key {path}")
            del node[last]
        else:
            if type(node.get(last)) is not list:
                raise FixtureError(f"{where}: append to non-list {path}")
            node[last].append(copy.deepcopy(spec["value"]))
    return doc


# -- closed-corpus structure ------------------------------------------------------


def _check_expect(expect, where):
    assert type(expect) is dict, where
    if expect == {"kind": "refusal"}:
        return
    assert set(expect) == {"kind", "checks"} and expect["kind"] == "document", where
    assert type(expect["checks"]) is list and expect["checks"], where
    for check in expect["checks"]:
        assert type(check) is dict and type(check["at"]) is list, where
        assert all(type(k) in (str, int) for k in check["at"]), where
        kind = set(check) - {"at"}
        assert kind in ({"equals"}, {"absent"}, {"keys"}), where
        if "absent" in check:
            assert check["absent"] is True, where
        if "keys" in check:
            assert type(check["keys"]) is list, where


def _check_row(row, where):
    assert type(row) is dict, where
    assert set(row) - {"then_baseline"} == ROW_KEYS, where
    assert type(row["name"]) is str and row["name"], where
    assert type(row["why"]) is str and row["why"], where
    assert type(row["mutations"]) is list, where
    if "then_baseline" in row:
        assert row["then_baseline"] is True, where
    _check_expect(row["expect"], where)
    _materialize(row["mutations"], where)


def _check(cases):
    assert type(cases) is dict and set(cases) == TOP_KEYS, sorted(cases)
    assert cases["schema_version"] == 1
    assert cases["contract"] == "data/contracts/openapi.yaml"
    assert cases["source"] == "data/contracts/control-plane.yaml"
    assert "separate binding" in cases["notes"]
    contract = yaml.safe_load((ROOT / cases["contract"]).read_text())
    assert cases["contract_schema_version"] == contract["schema_version"]
    assert hashlib.sha256(_canon(_shipped())).hexdigest() == cases["source_manifest"]
    assert set(cases["section_manifests"]) == set(SECTIONS)
    names = []
    for section in SECTIONS:
        rows = cases[section]
        assert type(rows) is list and rows, section
        manifest = cases["section_manifests"][section]
        assert list(manifest) == [r["name"] for r in rows], section
        for row in rows:
            _check_row(row, f"{section}:{row.get('name')}")
            assert manifest[row["name"]] == hashlib.sha256(_canon(row)).hexdigest()
        names.extend(r["name"] for r in rows)
    assert len(names) == len(set(names))


