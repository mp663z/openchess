HOSTILE = []


class _Armed:
    on = False


def _log(name):
    if _Armed.on:
        HOSTILE.append(name)


class _StrSub(str):
    pass


class _IntSub(int):
    pass


class _FloatSub(float):
    pass


class _DictSub(dict):
    pass


class _ListSub(list):
    pass


class _TupleBatch(tuple):
    pass


class _LyingDict(dict):
    def __getitem__(self, key):
        _log("getitem")
        return dict.__getitem__(self, key)

    def __iter__(self):
        _log("iter")
        return dict.__iter__(self)

    def __len__(self):
        _log("len")
        return dict.__len__(self)

    def keys(self):
        _log("keys")
        return dict.keys(self)

    def items(self):
        _log("items")
        return dict.items(self)

    def get(self, key, default=None):
        _log("get")
        return dict.get(self, key, default)


class _EqRaises(str):
    def __eq__(self, other):
        _log("eq")
        raise RuntimeError("hostile __eq__")

    def __hash__(self):
        _log("hash")
        return str.__hash__(self)


class _NonStrKey:
    """Hashes like the real key and raises on comparison."""

    def __init__(self, name):
        self.name = name

    def __hash__(self):
        _log("hash")
        return hash(self.name)

    def __eq__(self, other):
        _log("eq")
        raise RuntimeError("hostile __eq__")


class _ReprRaises(str):
    def __repr__(self):
        _log("repr")
        raise RuntimeError("hostile __repr__")

    def __str__(self):
        _log("str")
        raise RuntimeError("hostile __str__")

    def __format__(self, spec):
        _log("format")
        raise RuntimeError("hostile __format__")


class _GeneratorBatch:
    def __iter__(self):
        _log("iter")
        raise RuntimeError("hostile __iter__")


_STR_FIELDS = ("name", "operation_id", "event_id", "correlation_id", "outcome", "error_code")
_INT_FIELDS = ("version", "occurred_at")


def _rekey(mapping, field, make):
    return {(make(k) if k == field else k): v for k, v in mapping.items()}


def _event_variants(event):
    """(label, hostile event, expected failure class) for one accepted event."""
    out = [
        ("container-dict-subclass", _DictSub(event), "malformed_event"),
        ("container-lying-dict", _LyingDict(event), "malformed_event"),
        ("event-none", None, "malformed_event"),
        ("event-int", 7, "malformed_event"),
        ("event-string", "control_plane.x.succeeded", "malformed_event"),
        ("event-list-field-names", sorted(event), "malformed_event"),
    ]
    for field in event:
        out.append((f"key-str-subclass:{field}", _rekey(event, field, _StrSub), "malformed_event"))
        out.append((f"key-eq-raises:{field}", _rekey(event, field, _EqRaises), "malformed_event"))
        out.append((f"key-non-str:{field}", _rekey(event, field, _NonStrKey), "malformed_event"))
    for field in _STR_FIELDS:
        if field not in event:
            continue
        expected = "unknown_name" if field in ("name", "operation_id") else "malformed_event"
        out.append(
            (f"value-str-subclass:{field}", {**event, field: _StrSub(event[field])}, expected)
        )
        out.append(
            (f"value-eq-raises:{field}", {**event, field: _EqRaises(event[field])}, expected)
        )
        out.append(
            (f"value-repr-raises:{field}", {**event, field: _ReprRaises(event[field])}, expected)
        )
    for field in _INT_FIELDS:
        value = event[field]
        out.append(
            (f"value-int-subclass:{field}", {**event, field: _IntSub(value)}, "malformed_event")
        )
        out.append((f"value-bool:{field}", {**event, field: True}, "malformed_event"))
        out.append((f"value-float:{field}", {**event, field: float(value)}, "malformed_event"))
        out.append(
            (f"value-float-subclass:{field}", {**event, field: _FloatSub(value)}, "malformed_event")
        )
        out.append((f"value-str:{field}", {**event, field: str(value)}, "malformed_event"))
    return out


def _batch_variants(event):
    return [
        ("batch-list-subclass", _ListSub([event])),
        ("batch-tuple", tuple([event])),
        ("batch-dict", {"event": event}),
        ("batch-none", None),
        ("batch-string", "batch"),
        ("batch-generator", _GeneratorBatch()),
    ]


def _expect_typed_refusal(call, failure_class, watched, ledger=None):
    snaps = [_snap(item) for item in watched]
    HOSTILE.clear()
    _Armed.on = True
    try:
        try:
            call()
            got = "accepted"
        except _REF.Refusal as exc:
            got = (type(exc) is _REF.Refusal, exc.failure_class)
        except BaseException as exc:  # noqa: BLE001 - a raw escape is the failure
            got = ("raw", type(exc).__name__)
        calls = list(HOSTILE)
    finally:
        _Armed.on = False
    assert got == (True, failure_class), got
    assert calls == [], calls
    assert [_snap(item) for item in watched] == snaps, "hostile input was mutated"
    if ledger is not None:
        assert ledger.events == [] and ledger.seen == {}, "hostile input left a partial ledger"


def _hostile_event(event, label, hostile, failure_class):
    try:
        _expect_typed_refusal(lambda: _validate(hostile), failure_class, [hostile])
        ledger = _new_ledger()
        _expect_typed_refusal(
            lambda: _publish(ledger, [hostile]), failure_class, [hostile], ledger=ledger
        )
    except AssertionError as exc:
        raise AssertionError(f"{label}: {exc}") from None


def _hostile_batch(label, batch):
    try:
        ledger = _new_ledger()
        _expect_typed_refusal(lambda: _publish(ledger, batch), "malformed_event", [batch], ledger)
    except AssertionError as exc:
        raise AssertionError(f"{label}: {exc}") from None


