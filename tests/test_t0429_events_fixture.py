def _canon(case):
    return json.dumps(case, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()


def _check_event_shape(event, where):
    assert type(event) is dict, where
    assert set(event) - set(FIELDS) == set(), where
    assert set(REQUIRED) - set(event) == set(), where
    assert type(event["version"]) is int and event["version"] == 1, where
    assert event["operation_id"] in CATALOG, where
    assert event["outcome"] in ("succeeded", "failed"), where
    assert event["name"] == f"control_plane.{event['operation_id']}.{event['outcome']}", where
    for key in ("event_id", "correlation_id"):
        value = event[key]
        assert type(value) is str and 1 <= len(value) <= 64, where
        assert set(value) <= IDENTIFIER_CHARS, where
    assert type(event["occurred_at"]) is int and 0 <= event["occurred_at"] <= MAX_OCCURRED_AT, where
    if event["outcome"] == "failed":
        assert event["error_code"] in OPERATIONS[event["operation_id"]], where
    else:
        assert "error_code" not in event, where


def _check(cases):
    assert type(cases) is dict
    assert set(cases) == TOP_KEYS, f"top keys {sorted(cases)}"
    assert type(cases["schema_version"]) is int and cases["schema_version"] == 1
    assert cases["contract"] == "data/contracts/events.yaml"
    contract_doc = yaml.safe_load((ROOT / cases["contract"]).read_text())
    assert cases["contract_schema_version"] == contract_doc["schema_version"]
    assert type(cases["notes"]) is str and "synthetic" in cases["notes"]
    assert "provenance" in cases["notes"]
    assert set(cases["section_manifests"]) == set(SECTIONS)
    names = []
    for section in SECTIONS:
        rows = cases[section]
        assert type(rows) is list and rows, section
        manifest = cases["section_manifests"][section]
        assert type(manifest) is dict
        assert list(manifest) == [row["name"] for row in rows], section
        computed = {row["name"]: hashlib.sha256(_canon(row)).hexdigest() for row in rows}
        assert manifest == computed, section
        for row in rows:
            where = f"{section}:{row.get('name')}"
            assert set(row) == CASE_KEYS[section], where
            assert type(row["name"]) is str and row["name"], where
            names.append(row["name"])
        if section in ("happy", "boundary"):
            for row in rows:
                _check_event_shape(row["event"], f"{section}:{row['name']}")
        elif section == "malformed":
            for row in rows:
                assert row["expect_failure"] in FAILURE_CLASSES, row["name"]
                assert type(row["why"]) is str and row["why"], row["name"]
                _check_event_shape(row["minimal_repair"], f"malformed:{row['name']}:repair")
