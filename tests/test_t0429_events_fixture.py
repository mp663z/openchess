@pytest.mark.parametrize("name", _rollback_names())
def test_rollback_row(name):
    (row,) = [row for row in CASES["rollback"] if row["name"] == name]
    ledger = _new_ledger()
    for batch in row["published"]:
        attempt = copy.deepcopy(batch)
        _publish(ledger, attempt)
    assert len(ledger.events) == sum(
        len({event["event_id"] for event in batch}) for batch in row["published"]
    )
    if row["restart"]:
        ledger = _restart(ledger)
    before_events = copy.deepcopy(ledger.events)
    attempt = copy.deepcopy(row["batch"])
    attempt_snap = _snap(attempt)
    if row["expect_failure"] is None:
        assert _publish(ledger, attempt, fail_commit=row["inject_fault"]) == row["expect_published"]
    else:
        with pytest.raises(_REF.Refusal) as raised:
            _publish(ledger, attempt, fail_commit=row["inject_fault"])
        assert type(raised.value) is _REF.Refusal
        assert raised.value.failure_class == row["expect_failure"]
        assert ledger.events == before_events, "a refused batch left a partial publication"
    assert len(ledger.events) == row["expect_published"]
    assert _snap(attempt) == attempt_snap, "the refused/published attempt mutated its inputs"
    _assert_detached(ledger, [attempt])
    follow = copy.deepcopy(row["follow_up"])
    assert _publish(ledger, follow) == row["expect_after_follow_up"]
    _assert_detached(ledger, [follow])


