def _reference_block():
    source = inspect.getsource(_REF)
    tree = ast.parse(source)
    spans = []
    for node in tree.body:
        if (
            isinstance(node, ast.ClassDef)
            and node.name in ("Refusal", "Ledger")
            or isinstance(node, ast.FunctionDef)
            and node.name == "validate"
        ):
            spans.append((node.lineno, node.end_lineno))
    assert len(spans) == 3
    lines = source.splitlines()
    begin = min(start for start, _ in spans)
    end = max(finish for _, finish in spans)
    return "\n".join(lines[begin - 1 : end]) + "\n"


def _mutant_reference(name):
    old, new = {**REFERENCE_EDITS, **EQUIVALENT_EDITS}[name]
    source = _reference_block()
    assert old in source, name
    namespace = dict(vars(_REF))
    exec(compile(source.replace(old, new), f"<mutant {name}>", "exec"), namespace)  # noqa: S102
    return {key: namespace[key] for key in ("Refusal", "validate", "Ledger")}


def _fixture_red():
    """Labels of executed fixture checks that disagree with the reference
    currently bound; empty when green. Every check runs validate/publish on
    pinned or derived rows: no source-text or table-shape check counts."""
    red = []
    for section in ("happy", "boundary"):
        for row in CASES[section]:
            try:
                _run_accepted(row["event"])
            except BaseException:  # noqa: BLE001
                red.append(f"{section}:{row['name']}")
    for name in _malformed_names():
        for label, check in (
            (
                "",
                lambda name=name: test_malformed_row_refused_typed_without_echo_or_side_effect(
                    name
                ),
            ),
            ("repair", lambda name=name: test_malformed_minimal_repair_executes(name)),
        ):
            try:
                check()
            except BaseException:  # noqa: BLE001
                red.append(f"malformed:{name}{':' + label if label else ''}")
    for name in _rollback_names():
        try:
            test_rollback_row(name)
        except BaseException:  # noqa: BLE001
            red.append(f"rollback:{name}")
    for label, event in _HOSTILE_PROBES:
        try:
            for variant_label, hostile, failure_class in _event_variants(copy.deepcopy(event)):
                _hostile_event(event, variant_label, hostile, failure_class)
            for batch_label, batch in _batch_variants(copy.deepcopy(event)):
                _hostile_batch(batch_label, batch)
        except BaseException:  # noqa: BLE001
            red.append(f"hostile:{label}")
    return red


