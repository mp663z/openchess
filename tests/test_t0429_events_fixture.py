def _restart(ledger):
    """A fresh ledger restored from the persisted event sequence."""
    events = json.loads(json.dumps(ledger.events))
    fresh = _new_ledger()
    fresh.events = events
    fresh.seen = {event["event_id"]: event for event in events}
    return fresh


def _assert_detached(ledger, inputs):
    held = {id(node) for node in _containers_of(*inputs)}
    for committed in ledger.events:
        shared = [node for node in _containers_of(committed) if id(node) in held]
        assert shared == [], "the committed ledger shares a container with the caller's inputs"


def _run_accepted(event):
    ledger = _new_ledger()
    attempt = copy.deepcopy(event)
    assert _publish(ledger, [attempt]) == 1
    assert ledger.events == [event]
    assert _snap(ledger.events[0]) == _snap(event)
    _assert_detached(ledger, [attempt])
    # identical replay is a no-op, in-process and across a restart
    assert _publish(ledger, [copy.deepcopy(event)]) == 1
    assert ledger.events == [event]
    restored = _restart(ledger)
    assert _publish(restored, [copy.deepcopy(event)]) == 1
    assert restored.events == [event]


