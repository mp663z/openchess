def _containers_of(*roots):
    seen, out, stack = set(), [], list(reversed(roots))
    while stack:
        node = stack.pop()
        if isinstance(node, (dict, list)) and id(node) not in seen:
            seen.add(id(node))
            out.append(node)
            stack.extend(dict.values(node) if isinstance(node, dict) else list.__iter__(node))
    return out


def _snap_key(key):
    return str.__str__(key) if isinstance(key, str) else (type(key).__name__, repr(type(key)))


def _snap(obj, _seen=None):
    """Type-exact snapshot; aliases and cycles snapshot as references."""
    seen = {} if _seen is None else _seen
    if isinstance(obj, (dict, list)):
        if id(obj) in seen:
            return ("ref", seen[id(obj)])
        seen[id(obj)] = len(seen)
        if isinstance(obj, dict):
            body = [(type(obj).__name__, _snap_key(k), _snap(v, seen)) for k, v in dict.items(obj)]
        else:
            body = [_snap(v, seen) for v in list.__iter__(obj)]
        return (type(obj).__name__, body)
    if isinstance(obj, str):
        return (type(obj).__name__, str.__str__(obj))
    return (type(obj).__name__, obj)


