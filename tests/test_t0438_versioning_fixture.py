@pytest.mark.parametrize("section", SECTIONS)
def test_closed_manifest_detects_reorder_drop_and_extra(section):
    manifest = CASES["section_manifests"][section]
    names = [row["name"] for row in CASES[section]]
    assert list(manifest) == names
    assert len(names) == len(set(names))
    for mutant_rows in (
        list(reversed(CASES[section])),
        CASES[section][1:],
        [*CASES[section], copy.deepcopy(CASES[section][0])],
    ):
        mutant = copy.deepcopy(CASES)
        mutant[section] = mutant_rows
        with pytest.raises(AssertionError):
            _check_section(mutant, section)


def test_row_substitution_is_manifest_bound():
    for section in SECTIONS:
        rows = CASES[section]
        for target in range(len(rows)):
            for donor in range(len(rows)):
                if target == donor:
                    continue
                mutant_rows = copy.deepcopy(rows)
                replacement = copy.deepcopy(mutant_rows[donor])
                replacement["name"] = mutant_rows[target]["name"]
                mutant_rows[target] = replacement
                mutant = {**CASES, section: mutant_rows}
                with pytest.raises(AssertionError):
                    _check_section(mutant, section)


def test_each_row_field_is_manifest_bound():
    for section in SECTIONS:
        rows = CASES[section]
        for target in range(len(rows)):
            for donor in range(len(rows)):
                if target == donor:
                    continue
                shared = (set(rows[target]) & set(rows[donor])) - {"name"}
                for field in shared:
                    if rows[target][field] == rows[donor][field]:
                        continue
                    mutant_rows = copy.deepcopy(rows)
                    mutant_rows[target][field] = copy.deepcopy(rows[donor][field])
                    mutant = {**CASES, section: mutant_rows}
                    with pytest.raises(AssertionError):
                        _check_section(mutant, section)


