ROW_KEYS = {"name", "why", "old", "new", "old_minor", "new_minor", "expect"}
FAILURE = "malformed_version_request"
CEILING = 2147483647
ACTIONS = {
    "set": {"path", "value"},
    "del": {"path"},
    "append": {"path", "value"},
    "remove": {"path", "value"},
    "extend": {"path", "values"},
    "reverse": {"path"},
}


def _compare(old, new, old_minor, new_minor):
    """Late-bound access so mutant batteries can rebind the reference."""
    return _REF.compare(old, new, old_minor, new_minor)


# -- mutation materialization ---------------------------------------------------


class FixtureError(Exception):
    """A corpus row that cannot be materialized or refuses its own shape."""


def _walk(doc, path, where):
    node = doc
    for key in path[:-1]:
        if type(node) is not dict or type(key) is not str or key not in node:
            raise FixtureError(f"{where}: unresolvable path {path}")
        node = node[key]
    if type(node) is not dict or type(path[-1]) is not str:
        raise FixtureError(f"{where}: unresolvable path {path}")
    return node, path[-1]


def _apply(doc, mutations, where):
    for mutation in mutations:
        if type(mutation) is not dict or len(mutation) != 1:
            raise FixtureError(f"{where}: malformed mutation {mutation}")
        (action,) = mutation
        if action not in ACTIONS or set(mutation[action]) != ACTIONS[action]:
            raise FixtureError(f"{where}: malformed mutation {mutation}")
        spec = mutation[action]
        path = spec["path"]
        if type(path) is not list or not path or not all(type(key) is str for key in path):
            raise FixtureError(f"{where}: malformed path {path}")
        node, last = _walk(doc, path, where)
        if action == "set":
            node[last] = copy.deepcopy(spec["value"])
        elif action == "del":
            if last not in node:
                raise FixtureError(f"{where}: del of missing key {path}")
            del node[last]
        else:
            target = node.get(last)
            if type(target) is not list:
                raise FixtureError(f"{where}: list action on non-list {path}")
            if action == "append":
                target.append(copy.deepcopy(spec["value"]))
            elif action == "remove":
                if spec["value"] not in target:
                    raise FixtureError(f"{where}: remove of absent value {path}")
                target.remove(spec["value"])
            elif action == "extend":
                values = spec["values"]
                if type(values) is not list:
                    raise FixtureError(f"{where}: extend of non-list {path}")
                target.extend(copy.deepcopy(values))
            else:
                target.reverse()


def _materialize(descriptor, where):
    doc = copy.deepcopy(CASES["base_snapshot"])
    _apply(doc, descriptor, where)
    return doc


def _snapshots(row):
    where = f"row:{row['name']}"
    return (
        _materialize(row["old"], f"{where}:old"),
        _materialize(row["new"], f"{where}:new"),
    )


# -- closed-corpus structure ------------------------------------------------------


def _canon(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()


def _check_mutation_lists(row, where):
    for side in ("old", "new"):
        mutations = row[side]
        assert type(mutations) is list, where
        for mutation in mutations:
            assert type(mutation) is dict and len(mutation) == 1, where
            (action,) = mutation
            assert action in ACTIONS, where
            assert set(mutation[action]) == ACTIONS[action], where
            path = mutation[action]["path"]
            assert type(path) is list and path, where
            assert all(type(key) is str for key in path), where
        # every mutation must materialize against the pinned base snapshot
        _materialize(mutations, f"{where}:{side}")


def _check_row(row, section, where):
    assert type(row) is dict and set(row) == ROW_KEYS, where
    assert type(row["name"]) is str and row["name"], where
    assert type(row["why"]) is str and row["why"], where
    _check_mutation_lists(row, where)
    if section == "malformed":
        assert row["expect"] == FAILURE, where
    else:
        assert type(row["expect"]) is bool, where
        for key in ("old_minor", "new_minor"):
            minor = row[key]
            assert type(minor) is int and 0 <= minor <= CEILING, where


def _check_section(cases, section):
    """The manifest closure for one section: digests, order, key shapes."""
    rows = cases[section]
    assert type(rows) is list and rows, section
    manifest = cases["section_manifests"][section]
    assert list(manifest) == [row["name"] for row in rows], section
    computed = {row["name"]: hashlib.sha256(_canon(row)).hexdigest() for row in rows}
    assert manifest == computed, section
    for row in rows:
        _check_row(row, section, f"{section}:{row.get('name')}")


def _check(cases):
    assert type(cases) is dict
    assert set(cases) == TOP_KEYS, f"top keys {sorted(cases)}"
    assert type(cases["schema_version"]) is int and cases["schema_version"] == 1
    assert cases["contract"] == "data/contracts/control_plane_versioning.yaml"
    assert cases["contract_schema_version"] == CONTRACT_DOC["schema_version"]
    assert cases["source"] == "data/contracts/control-plane.yaml"
    assert type(cases["notes"]) is str and "separate binding" in cases["notes"]
    base = cases["base_snapshot"]
    assert type(base) is dict and set(base) == {"schema_version", "contract", "areas"}
    assert hashlib.sha256(_canon(base)).hexdigest() == cases["base_manifest"]
    assert set(cases["section_manifests"]) == set(SECTIONS)
    names = []
    for section in SECTIONS:
        _check_section(cases, section)
        names.extend(row["name"] for row in cases[section])
    assert len(names) == len(set(names))


