# -- mutant battery ---------------------------------------------------------------

REFERENCE_EDITS = dict(_REF.REFERENCE_MUTANTS)
EQUIVALENT_EDITS = dict(_REF.EQUIVALENT)


def _equivalent_compare(name):
    before, replacement, _probe = EQUIVALENT_EDITS[name]
    source = (
        inspect.getsource(_REF._fields)
        + "\n"
        + inspect.getsource(_REF._minor)
        + "\n"
        + inspect.getsource(_REF.compare)
    )
    assert source.count(before) == 1, name
    scope = dict(vars(_REF))
    exec(  # noqa: S102
        compile(ast.parse(source.replace(before, replacement, 1)), f"<equivalent:{name}>", "exec"),
        scope,
    )
    return scope["compare"]


def _fixture_red():
    """Labels of executed fixture rows that disagree with the reference
    currently bound; empty when green. Every label comes from a row executed
    through compare(): no source-text or table-shape check counts."""
    red = []
    for section in VERDICT_SECTIONS:
        for row in CASES[section]:
            try:
                _run_verdict_row(row)
            except BaseException:  # noqa: BLE001
                red.append(f"{section}:{row['name']}")
    for row in CASES["malformed"]:
        try:
            _run_malformed_row(row)
        except BaseException:  # noqa: BLE001
            red.append(f"malformed:{row['name']}")
    return red


def test_reference_edits_apply():
    for name in REFERENCE_EDITS:
        _REF._mutant_compare(name)
    for name in EQUIVALENT_EDITS:
        _equivalent_compare(name)


def test_reference_is_green():
    assert _fixture_red() == []


@pytest.mark.parametrize("name", sorted(REFERENCE_EDITS))
def test_reference_mutants_turn_the_fixture_red(name, monkeypatch):
    monkeypatch.setattr(_REF, "compare", _REF._mutant_compare(name))
    assert _fixture_red() != [], name


@pytest.mark.parametrize("name", sorted(EQUIVALENT_EDITS))
def test_equivalent_edits_keep_the_fixture_green(name, monkeypatch):
    monkeypatch.setattr(_REF, "compare", _equivalent_compare(name))
    assert _fixture_red() == [], name
