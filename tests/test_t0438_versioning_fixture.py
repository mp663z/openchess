"""T0438: closed, executable fixture for the v1 control-plane versioning
contract.

The corpus (tests/fixtures/control-plane-versioning/cases.json, generated by
tools/versioning_fixture_generate.py) pins the base snapshot once plus exact
mutation lists that materialize each row's old/new snapshots, and executes
every row against the T0437 test-only reference compare() as a separate
binding. Expectations are authored from the structured contract
(data/contracts/control_plane_versioning.yaml), never computed by the
reference. The mutant battery's kills all come from executed fixture rows,
never source-text checks; the T0437 equivalent edits, preempted by strict
T0419 source validation, must keep the fixture green.
"""

