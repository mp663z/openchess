# -- executed rows --------------------------------------------------------------


def _run_verdict_row(row):
    old, new = _snapshots(row)
    before = copy.deepcopy((old, new))
    first = _compare(old, new, row["old_minor"], row["new_minor"])
    second = _compare(old, new, row["old_minor"], row["new_minor"])
    assert first is row["expect"], row["name"]
    assert second is row["expect"], row["name"]
    assert (old, new) == before, row["name"]


def _run_malformed_row(row):
    old, new = _snapshots(row)
    before = copy.deepcopy((old, new))
    errors = []
    for _ in range(2):
        with pytest.raises(_REF.VersionError) as caught:
            _compare(old, new, row["old_minor"], row["new_minor"])
        errors.append(caught.value)
    assert errors[0] is not errors[1], row["name"]
    for error in errors:
        assert error.failure_class == FAILURE, row["name"]
        assert error.code == "malformed_request", row["name"]
        assert error.retryable is False, row["name"]
        assert error.__cause__ is None and error.__context__ is None, row["name"]
    assert (old, new) == before, row["name"]


def _section_names(section):
    return [row["name"] for row in CASES[section]]


def _verdict_row(section, name):
    return next(row for row in CASES[section] if row["name"] == name)


@pytest.mark.parametrize(
    "section,name",
    [(section, name) for section in VERDICT_SECTIONS for name in _section_names(section)],
    ids=lambda value: value if value in SECTIONS else None,
)
def test_verdict_rows_execute_with_purity_and_determinism(section, name):
    _run_verdict_row(_verdict_row(section, name))


@pytest.mark.parametrize("name", _section_names("malformed"))
def test_malformed_rows_refuse_typed_with_purity(name):
    _run_malformed_row(_verdict_row("malformed", name))


