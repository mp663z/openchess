def _check_typed_refusal(error, name, where):
    assert type(error) is _REF.ErrorsError, where
    assert error.failure_class == FAILURE, where
    assert error.code == "malformed_request", where
    assert error.retryable is False, where
    assert error.__cause__ is None, where
    if name in CONTEXT_CARRYING:
        assert error.__context__ is not None, where
    else:
        assert error.__context__ is None, where
    for marker in NO_ECHO:
        assert marker not in str(error), where
        assert marker not in repr(error), where


def _run_verdict_call(status, operation, payload, source_mutations, expect, where):
    source = _materialize_source(source_mutations, where)
    source_snap = _snap(source)
    payload_snap = _snap(payload)
    first = _classify(source, status, payload, operation)
    second = _classify(source, status, payload, operation)
    assert first == expect, where
    assert second == expect, where
    assert first is not second, where  # a fresh dict per classification
    if first["kind"] == "error":
        assert first is not payload["error"], where
        mutated = copy.deepcopy(payload)
        mutated["error"]["message"] = "mutated-after-classification"
        assert first["message"] == expect["message"], where
    assert _snap(payload) == payload_snap, where
    assert _snap(source) == source_snap, where


def _run_refusal_call(status, operation, payload, source_mutations, name, where):
    source = _materialize_source(source_mutations, where)
    source_snap = _snap(source)
    payload_snap = _snap(payload)
    errors = []
    for _ in range(2):
        with pytest.raises(_REF.ErrorsError) as caught:
            _classify(source, status, payload, operation)
        errors.append(caught.value)
    assert errors[0] is not errors[1], where  # a fresh typed error per refusal
    for error in errors:
        _check_typed_refusal(error, name, where)
    assert _snap(payload) == payload_snap, where
    assert _snap(source) == source_snap, where
    return errors


def _run_verdict_row(row, where):
    _run_verdict_call(
        row["status"], row["operation"], row["payload"], row.get("source", []), row["expect"], where
    )


def _run_refusal_row(row, where):
    return _run_refusal_call(
        row["status"], row["operation"], row["payload"], row.get("source", []), row["name"], where
    )


def _run_rollback_row(row):
    where = f"rollback:{row['name']}"
    all_errors = []
    for index, call in enumerate(row["calls"]):
        call_where = f"{where}:call{index}"
        if "expect_failure" in call:
            all_errors += _run_refusal_call(
                call["status"],
                call["operation"],
                call["payload"],
                call["source"],
                row["name"],
                call_where,
            )
        else:
            _run_verdict_call(
                call["status"],
                call["operation"],
                call["payload"],
                call["source"],
                call["expect"],
                call_where,
            )
    ids = {id(error) for error in all_errors}
    assert len(ids) == len(all_errors), where  # no typed error is ever reused


