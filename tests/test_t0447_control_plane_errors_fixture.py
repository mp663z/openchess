def _check_call(call, where):
    assert type(call) is dict and set(call) <= CALL_KEYS, where
    assert {"status", "operation", "payload", "source"} <= set(call), where
    assert ("expect" in call) != ("expect_failure" in call), where
    if "expect" in call:
        # accepted calls use the real surface: null or a declared operation
        assert type(call["operation"]) is str or call["operation"] is None, where
        if type(call["operation"]) is str:
            assert call["operation"] in OPERATIONS, where
    _check_mutation_lists(call["source"], where)
    if "expect_failure" in call:
        assert call["expect_failure"] in FAILURE_CLASSES, where
    else:
        _check_verdict_expect(call, where)


def _check_row(row, section, where):
    assert type(row) is dict, where
    assert type(row["name"]) is str and row["name"], where
    assert type(row["why"]) is str and row["why"], where
    if section in VERDICT_SECTIONS:
        assert set(row) == VERDICT_KEYS, where
        assert type(row["status"]) is int and (
            200 <= row["status"] <= 299 or 400 <= row["status"] <= 599
        ), where
        assert type(row["payload"]) is dict, where
        _check_call(
            {key: row[key] for key in VERDICT_KEYS - {"name", "why"}} | {"source": []}, where
        )
    elif section == "malformed":
        assert set(row) == MALFORMED_KEYS, where
        assert row["expect_failure"] in FAILURE_CLASSES, where
        _check_call({key: row[key] for key in MALFORMED_KEYS - {"name", "why"}}, where)
    else:
        assert set(row) == ROLLBACK_KEYS, where
        calls = row["calls"]
        assert type(calls) is list and calls, where
        for index, call in enumerate(calls):
            _check_call(call, f"{where}:call{index}")


def _check_section(cases, section):
    """The manifest closure for one section: digests, order, key shapes."""
    rows = cases[section]
    assert type(rows) is list and rows, section
    manifest = cases["section_manifests"][section]
    assert list(manifest) == [row["name"] for row in rows], section
    computed = {row["name"]: hashlib.sha256(_canon(row)).hexdigest() for row in rows}
    assert manifest == computed, section
    for row in rows:
        _check_row(row, section, f"{section}:{row.get('name')}")


