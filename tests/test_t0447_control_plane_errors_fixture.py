# -- type-exact snapshots -----------------------------------------------------


def _containers_of(*roots):
    seen, out, stack = set(), [], list(reversed(roots))
    while stack:
        node = stack.pop()
        if isinstance(node, (dict, list)) and id(node) not in seen:
            seen.add(id(node))
            out.append(node)
            stack.extend(dict.values(node) if isinstance(node, dict) else list.__iter__(node))
    return out


def _snap_key(key):
    return str.__str__(key) if isinstance(key, str) else (type(key).__name__, repr(type(key)))


def _snap(obj, _seen=None):
    """Type-exact snapshot; aliases and cycles snapshot as references."""
    seen = {} if _seen is None else _seen
    if isinstance(obj, (dict, list)):
        if id(obj) in seen:
            return ("ref", seen[id(obj)])
        seen[id(obj)] = len(seen)
        if isinstance(obj, dict):
            body = [(type(obj).__name__, _snap_key(k), _snap(v, seen)) for k, v in dict.items(obj)]
        else:
            body = [_snap(v, seen) for v in list.__iter__(obj)]
        return (type(obj).__name__, body)
    if isinstance(obj, str):
        return (type(obj).__name__, str.__str__(obj))
    if isinstance(obj, float) and obj != obj:
        return (type(obj).__name__, "nan")
    return (type(obj).__name__, obj)


# -- source materialization ---------------------------------------------------


class FixtureError(Exception):
    """A corpus mutation list that cannot be materialized or is malformed."""


def _walk(doc, path, where):
    node = doc
    for key in path[:-1]:
        if type(node) is not dict or type(key) is not str or key not in node:
            raise FixtureError(f"{where}: unresolvable path {path}")
        node = node[key]
    if type(node) is not dict or type(path[-1]) is not str:
        raise FixtureError(f"{where}: unresolvable path {path}")
    return node, path[-1]


def _apply_source_mutations(doc, mutations, where):
    for mutation in mutations:
        if type(mutation) is not dict or len(mutation) != 1:
            raise FixtureError(f"{where}: malformed mutation {mutation}")
        (action,) = mutation
        spec = mutation[action]
        if (
            action not in MUTATION_ACTIONS
            or type(spec) is not dict
            or set(spec) != MUTATION_ACTIONS[action]
        ):
            raise FixtureError(f"{where}: malformed mutation {mutation}")
        path = spec["path"]
        if type(path) is not list or not path or not all(type(key) is str for key in path):
            raise FixtureError(f"{where}: malformed path {path}")
        node, last = _walk(doc, path, where)
        if action == "set":
            node[last] = copy.deepcopy(spec["value"])
        else:
            if last not in node:
                raise FixtureError(f"{where}: del of missing key {path}")
            del node[last]


def _materialize_source(mutations, where):
    doc = copy.deepcopy(SOURCE_DOC)
    _apply_source_mutations(doc, mutations, where)
    return doc


