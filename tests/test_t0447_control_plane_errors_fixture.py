def _fixture_red():
    """Labels of executed fixture checks that disagree with the reference
    currently bound; empty when green. Every label comes from a row or probe
    executed through classify(): no source-text or table-shape check counts."""
    red = []
    for section in VERDICT_SECTIONS:
        for row in CASES[section]:
            try:
                _run_verdict_row(row, f"{section}:{row['name']}")
            except BaseException:  # noqa: BLE001
                red.append(f"{section}:{row['name']}")
    for row in CASES["malformed"]:
        try:
            _run_refusal_row(row, f"malformed:{row['name']}")
        except BaseException:  # noqa: BLE001
            red.append(f"malformed:{row['name']}")
