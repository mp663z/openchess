# Edits that must NOT change behavior: pure reorders of equivalent checks.
EQUIVALENT_EDITS = {
    "field-loop-order": (
        'for field in ("code", "message", "retryable"):',
        'for field in ("message", "code", "retryable"):',
    ),
    "status-range-order": (
        "200 <= status <= 299 or 400 <= status <= 599",
        "400 <= status <= 599 or 200 <= status <= 299",
    ),
    "secret-set-order": (
        '{"key_material", "password_hash_client", "token", "secret"}',
        '{"secret", "token", "password_hash_client", "key_material"}',
    ),
}


def _reference_source():
    return "\n".join(
        inspect.getsource(f)
        for f in (
            _REF._text,
            _REF._tokens,
            _REF._fen_placement_in,
            _REF._safe_key,
            _REF._json_safe,
            _REF._source,
            _REF.classify,
        )
    )


def _equivalent_classify(name):
    before, replacement = EQUIVALENT_EDITS[name]
    source = _reference_source()
    assert source.count(before) == 1, name
    scope = dict(vars(_REF))
    exec(  # noqa: S102
        compile(ast.parse(source.replace(before, replacement, 1)), f"<equivalent:{name}>", "exec"),
        scope,
    )
    return scope["classify"]


def test_reference_edits_apply():
    for name in _REF.REFERENCE_MUTANTS:
        _REF._mutant(name)
    for name in EQUIVALENT_EDITS:
        _equivalent_classify(name)


