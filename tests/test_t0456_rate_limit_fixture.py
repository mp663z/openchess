def _rebind(before, after, name):
    source = inspect.getsource(_REF.decision)
    assert source.count(before) == 1, name
    scope = dict(vars(_REF))
    exec(  # noqa: S102
        compile(ast.parse(source.replace(before, after, 1)), f"<rate-limit:{name}>", "exec"),
        scope,
    )
    return scope["decision"]


