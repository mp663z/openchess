class _StrSub(str):
    pass


class _IntSub(int):
    pass


class _DictSub(dict):
    pass


def _probe_base():
    return copy.deepcopy(_row_by_name("happy", "admit-first-empty-login")["call"])


def _field_probes():
    """(label, edited call, refusal code) probes: every value here is outside
    JSON's representational scope."""
    probes = []

    def add(label, edit, code="malformed_request"):
        call = _probe_base()
        edit(call)
        probes.append((label, call, code))

    add("operation-str-subclass", lambda c: c.update(operation=_StrSub("identity.login")))
    add("operation-plain-object", lambda c: c.update(operation=object()))
    add("account-str-subclass", lambda c: c.update(account=_StrSub("opaque:account")))
    add("account-plain-object", lambda c: c.update(account=object()))
    add("source-str-subclass", lambda c: c.update(source=_StrSub("opaque:source")))
    add("now-int-subclass", lambda c: c.update(now=_IntSub(0)))
    add("now-nan", lambda c: c.update(now=float("nan")))
    add("now-infinity", lambda c: c.update(now=float("inf")))
    add("policy-dict-subclass", lambda c: c.update(policy=_DictSub(c["policy"])))
    add("policy-version-int-subclass", lambda c: c["policy"].update(version=_IntSub(1)))
    add("policy-capacity-nan", lambda c: c["policy"]["account"].update(capacity=float("nan")))
    return probes


