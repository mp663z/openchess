    for name, (before, after, _why) in REFERENCE_MUTANTS.items():
        mutant = _rebind(before, after, name)
        assert mutant is not _REF.decision
    for name, (before, after) in EQUIVALENT_EDITS.items():
        _rebind(before, after, name)


