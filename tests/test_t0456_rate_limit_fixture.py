# -- type-exact snapshots -----------------------------------------------------


def _snap(obj, _seen=None):
    """Type-exact snapshot; aliases and cycles snapshot as references."""
    seen = {} if _seen is None else _seen
    if isinstance(obj, (dict, list)):
        if id(obj) in seen:
            return ("ref", seen[id(obj)])
        seen[id(obj)] = len(seen)
        if isinstance(obj, dict):
            body = [
                (
                    type(obj).__name__,
                    str.__str__(k) if isinstance(k, str) else (type(k).__name__, repr(type(k))),
                    _snap(v, seen),
                )
                for k, v in dict.items(obj)
            ]
        else:
            body = [_snap(v, seen) for v in list.__iter__(obj)]
        return (type(obj).__name__, body)
    if isinstance(obj, str):
        return (type(obj).__name__, str.__str__(obj))
    if isinstance(obj, float) and obj != obj:
        return (type(obj).__name__, "nan")
    if obj is None or type(obj) in (bool, int, float):
        return (type(obj).__name__, obj)
    return (type(obj).__name__, repr(type(obj)))


# -- state adapter --------------------------------------------------------------


def _to_ref_state(records):
    """Fixture records to the reference's tuple-keyed snapshot."""
    return {
        (rec["operation"], rec["scope"], rec["opaque"]): (rec["window"], rec["count"])
        for rec in records
    }


def _canon_records(records):
    return sorted(
        (json.dumps(rec, sort_keys=True, separators=(",", ":")) for rec in records),
    )


def _canon_ref_state(state):
    return _canon_records(
        {
            "operation": key[0],
            "scope": key[1],
            "opaque": key[2],
            "window": value[0],
            "count": value[1],
        }
        for key, value in state.items()
    )


def _args(call, ref_state=_UNSET):
    args = dict(call)
    args["state"] = _to_ref_state(call["state"]) if ref_state is _UNSET else ref_state
    return args


# -- executed calls ---------------------------------------------------------------


def _run_verdict_call(call, expect, where, ref_state=_UNSET):
    outcome = expect["outcome"]
    assert outcome in OUTCOMES, where
    args = _args(call, ref_state)
    snap = _snap(args)
    if outcome == "deny":
        errors = []
        for run_args in (copy.deepcopy(args), args):  # second run borrows the caller's objects
            with pytest.raises(_REF.Refusal) as caught:
                _decide(**run_args)
            assert type(caught.value) is _REF.Refusal, where
            assert caught.value.code == "rate_limited", where
            errors.append(caught.value)
        assert errors[0] is not errors[1], where
        assert _snap(args) == snap, where  # a denial commits neither counter
        return
    results = []
    for run_args in (copy.deepcopy(args), args):  # second run borrows the caller's objects
        kind, new_state = _decide(**run_args)
        assert kind == outcome, where
        assert new_state is not run_args["state"], where  # detached result state
        assert _canon_ref_state(new_state) == _canon_records(expect["state"]), where
        results.append(new_state)
    assert results[0] is not results[1], where
    assert _snap(args) == snap, where  # the decision never mutates its inputs


def _run_refusal_call(call, code, where, ref_state=_UNSET):
    assert code in FAILURE_CODES, where
    args = _args(call, ref_state)
    snap = _snap(args)
    errors = []
    for run_args in (copy.deepcopy(args), args):  # second run borrows the caller's objects
        with pytest.raises(_REF.Refusal) as caught:
            _decide(**run_args)
        errors.append(caught.value)
    assert errors[0] is not errors[1], where  # a fresh typed error per refusal
    for error in errors:
        assert type(error) is _REF.Refusal, where
        assert error.code == code, where
    assert _snap(args) == snap, where  # a refusal commits nothing
    return errors


def _run_verdict_row(row, where):
    _run_verdict_call(row["call"], row["expect"], where)


def _run_refusal_row(row, where):
    return _run_refusal_call(row["call"], row["expect_failure"], where)


def _run_rollback_row(row):
    where = f"rollback:{row['name']}"
    threaded = None
    all_errors = []
    for index, entry in enumerate(row["calls"]):
        step_where = f"{where}:call{index}"
        call = entry["call"]
        if threaded is not None:
            # The pinned chain: each step starts from exactly the state the
            # previous step pinned as its outcome.
            assert _canon_records(call["state"]) == threaded, step_where
        if "expect_failure" in entry:
            all_errors += _run_refusal_call(call, entry["expect_failure"], step_where)
            threaded = _canon_records(call["state"])
        else:
            _run_verdict_call(call, entry["expect"], step_where)
            threaded = _canon_records(entry["expect"]["state"])
    ids = {id(error) for error in all_errors}
    assert len(ids) == len(all_errors), where  # no typed error is ever reused


# -- closed-corpus structure ---------------------------------------------------


def _canon(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()


def _check_record(rec, where):
    assert type(rec) is dict and set(rec) == RECORD_KEYS, where
    assert type(rec["operation"]) is str, where
    assert type(rec["scope"]) is str and rec["scope"], where
    assert type(rec["opaque"]) is str and rec["opaque"], where
    assert type(rec["window"]) is int and rec["window"] >= 0, where
    assert type(rec["count"]) is int and rec["count"] >= 0, where


def _check_strict_call(call, where):
    assert type(call) is dict and set(call) == CALL_KEYS, where
    assert call["operation"] in OPS, where
    for label in ("account", "source"):
        value = call[label]
        assert type(value) is str and value.startswith("opaque:"), where
    assert type(call["now"]) is int and 0 <= call["now"] <= MAX_CLOCK, where
    policy = call["policy"]
    assert type(policy) is dict and set(policy) == {"version", "account", "source"}, where
    assert type(policy["version"]) is int and policy["version"] >= 1, where
    for label in ("account", "source"):
        cfg = policy[label]
        assert type(cfg) is dict and set(cfg) == {"capacity", "window_ms"}, where
        for key in ("capacity", "window_ms"):
            assert type(cfg[key]) is int and 1 <= cfg[key] <= MAX_CLOCK, where
    assert type(call["state"]) is list, where
    for index, rec in enumerate(call["state"]):
        _check_record(rec, f"{where}:state{index}")
    keys = [(rec["operation"], rec["scope"], rec["opaque"]) for rec in call["state"]]
    assert len(keys) == len(set(keys)), where
    assert call["replay"] in ("new", "cached"), where
    for flag in ("body_same", "store_available", "effect_ok"):
        assert type(call[flag]) is bool, where


def _check_verdict_expect(row, where):
    expect = row["expect"]
    assert type(expect) is dict and set(expect) == {"outcome", "state"}, where
    outcome = expect["outcome"]
    assert outcome in OUTCOMES, where
    assert type(expect["state"]) is list, where
    for index, rec in enumerate(expect["state"]):
        _check_record(rec, f"{where}:expect{index}")
    call = row["call"]
    if outcome == "replay":
        assert call["replay"] == "cached" and call["body_same"] is True, where
        assert _canon_records(expect["state"]) == _canon_records(call["state"]), where
    elif outcome == "deny":
        assert call["replay"] == "new", where
        assert _canon_records(expect["state"]) == _canon_records(call["state"]), where
    else:
        assert call["replay"] == "new", where


def _check_lenient_call(call, where):
    """Malformed rows carry hostile values; only the envelope is closed."""
    assert type(call) is dict and set(call) == CALL_KEYS, where
    assert type(call["state"]) is list, where
    for index, rec in enumerate(call["state"]):
        assert type(rec) is dict and set(rec) == RECORD_KEYS, f"{where}:state{index}"


def _check_row(row, section, where):
    assert type(row) is dict, where
    assert type(row["name"]) is str and row["name"], where
    assert type(row["why"]) is str and row["why"], where
    if section in VERDICT_SECTIONS:
        assert set(row) == VERDICT_ROW_KEYS, where
        _check_strict_call(row["call"], where)
        _check_verdict_expect(row, where)
    elif section == "malformed":
        assert set(row) == MALFORMED_ROW_KEYS, where
        assert row["expect_failure"] in FAILURE_CODES, where
        _check_lenient_call(row["call"], where)
    else:
        assert set(row) == ROLLBACK_ROW_KEYS, where
        calls = row["calls"]
        assert type(calls) is list and calls, where
        for index, entry in enumerate(calls):
            step_where = f"{where}:call{index}"
            assert type(entry) is dict and set(entry) <= STEP_KEYS, step_where
            assert "call" in entry, step_where
            assert ("expect" in entry) != ("expect_failure" in entry), step_where
            if "expect_failure" in entry:
                assert entry["expect_failure"] in FAILURE_CODES, step_where
                _check_lenient_call(entry["call"], step_where)
            else:
                _check_strict_call(entry["call"], step_where)
                _check_verdict_expect(
                    {"call": entry["call"], "expect": entry["expect"]}, step_where
                )


def _check_section(cases, section):
    """The manifest closure for one section: digests, order, key shapes."""
    rows = cases[section]
    assert type(rows) is list and rows, section
    manifest = cases["section_manifests"][section]
    assert list(manifest) == [row["name"] for row in rows], section
    computed = {row["name"]: hashlib.sha256(_canon(row)).hexdigest() for row in rows}
    assert manifest == computed, section
    for row in rows:
        _check_row(row, section, f"{section}:{row.get('name')}")


